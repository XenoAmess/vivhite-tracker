    // 常规池之外（含邓煜），防连续重复
    fun randomExcept(lastIndex: Int?, random: Random = Random.Default): Int {
        require(pool.isNotEmpty())
        if (pool.size == 1) return 0
        var index: Int
        do {
            index = random.nextInt(pool.size)
        } while (index == lastIndex)
        return index
    }
